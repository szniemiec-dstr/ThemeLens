    public static Glyph Get(char c) => Glyphs.TryGetValue(c, out Glyph? g) ? g : Glyphs['?'];

    /// <summary>Width of a run of text in font units.</summary>
    public static float Measure(string text)
    {
        float width = 0;
        foreach (char c in text)
        {
            width += Get(c).Width + Gap;
        }

        return text.Length == 0 ? 0 : width - Gap;
    }

